"""
World News in One Image — 19 November 2026
make.fun bounty #3 (free entry): "Sum up 19 November's world news in one image".

Reads the STORIES list below and renders a single 1200x675 PNG summary
(news-2026-11-19.png) with Pillow. No network access, no external assets:
all drawing is done with the standard library + Pillow and system fonts
(DejaVu Sans, with Liberation Sans as fallback).

Usage:
    python3 generate.py            # writes news-2026-11-19.png next to this script
    python3 generate.py -o out.png # custom output path
"""
